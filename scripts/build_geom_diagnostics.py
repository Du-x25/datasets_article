"""Build verified per-scene geometric pipeline diagnostic tables and macros.

Inputs (bundled under figures/source_data/):
- acquisition_provenance.csv
- scene_quality_summary.csv

Outputs (under generated/):
- geom_diagnostics_zh.tex
- geom_diagnostics_en.tex
- geom_macros.tex
"""
from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "figures/source_data"
GEN = ROOT / "generated"


def load_rows():
    with (SRC / "acquisition_provenance.csv").open(encoding="utf-8-sig", newline="") as f:
        prov = {r["scene"]: r for r in csv.DictReader(f)}
    with (SRC / "scene_quality_summary.csv").open(encoding="utf-8-sig", newline="") as f:
        qual = {r["scene"]: r for r in csv.DictReader(f)}
    rows = []
    for idx in range(1, 11):
        sc = f"C{idx}"
        p, q = prov[sc], qual[sc]
        w, h = int(p["canvas_width"]), int(p["canvas_height"])
        assert (w, h) == (int(q["width"]), int(q["height"])), f"dimension mismatch at {sc}"
        preview_scale = max(w, h) / 1200.0
        holdout_prev = float(q["rgb_b1_holdout_p95_preview_px"])
        holdout_out = holdout_prev * preview_scale
        corner_prev = float(q["rgb_b1_identity_corner_deviation_preview_px"])
        intra_out = float(q["maximum_intra_swir_output_p95_px"])
        ba = p["bundle_adjustment_enabled"].strip().lower() == "true"
        rows.append({
            "scene": sc,
            "pose_model": p["pose_model"],
            "ba": ba,
            "ba_before": float(p["bundle_adjustment_train_rms_before_px"]) if ba else None,
            "ba_after": float(p["bundle_adjustment_train_rms_after_px"]) if ba else None,
            "ba_holdout_p95": float(p["bundle_adjustment_holdout_p95_px"]) if ba else None,
            "pose_edges": int(p["accepted_pose_edges"]),
            "cov_uncropped": float(p["common_coverage_fraction_uncropped"]) * 100.0,
            "holdout_prev": holdout_prev,
            "holdout_out": holdout_out,
            "corner_prev": corner_prev,
            "intra_out": intra_out,
        })
    return rows


def build_table(rows, lang: str) -> str:
    if lang == "zh":
        head = (
            r"地点 & 模型 & 边数 & \shortstack{BA前后\\RMS/px} & "
            r"\shortstack{RGB--B1留出P95\\(预览/输出px)} & \shortstack{角点偏移\\预览px} & "
            r"\shortstack{SWIR波段内P95\\输出px} & \shortstack{共同覆盖\\(\%)} \\"
        )
        model_label = lambda r: ("单应+BA" if r["pose_model"] == "homography" else "仿射")
    else:
        head = (
            r"Site & \shortstack{Pose\\model} & Edges & \shortstack{BA RMS\\pre/post px} & "
            r"\shortstack{RGB--B1 holdout\\P95 (prev/out)} & \shortstack{Corner dev.\\prev px} & "
            r"\shortstack{Intra-SWIR\\P95 (out px)} & \shortstack{Common\\cov./\%} \\"
        )
        model_label = lambda r: ("Homog.+BA" if r["pose_model"] == "homography" else "Affine")

    lines = [
        "% Generated by scripts/build_geom_diagnostics.py; do not edit manually.",
        r"\begin{tabular}{@{}llrrrrrrr@{}}",
        r"\toprule",
        head,
        r"\midrule",
    ]
    for r in rows:
        ba_str = f"{r['ba_before']:.2f}/{r['ba_after']:.2f}" if r["ba"] else "--"
        lines.append(
            f"{r['scene']} & {model_label(r)} & {r['pose_edges']} & {ba_str} & "
            f"{r['holdout_prev']:.2f} / {r['holdout_out']:.2f} & {r['corner_prev']:.2f} & "
            f"{r['intra_out']:.2f} & {r['cov_uncropped']:.1f} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def build_macros(rows) -> str:
    hp = [r["holdout_prev"] for r in rows]
    ho = [r["holdout_out"] for r in rows]
    cp = [r["corner_prev"] for r in rows]
    sw = [r["intra_out"] for r in rows]
    ba_b = [r["ba_before"] for r in rows if r["ba"]]
    ba_a = [r["ba_after"] for r in rows if r["ba"]]
    ba_h = [r["ba_holdout_p95"] for r in rows if r["ba"]]
    cov = [r["cov_uncropped"] for r in rows]
    pairs = [
        ("GeomRgbBOnePrevMin", f"{min(hp):.2f}"),
        ("GeomRgbBOnePrevMax", f"{max(hp):.2f}"),
        ("GeomRgbBOneOutMin", f"{min(ho):.2f}"),
        ("GeomRgbBOneOutMax", f"{max(ho):.2f}"),
        ("GeomCornerPrevMin", f"{min(cp):.2f}"),
        ("GeomCornerPrevMax", f"{max(cp):.2f}"),
        ("GeomIntraSwirMin", f"{min(sw):.2f}"),
        ("GeomIntraSwirMax", f"{max(sw):.2f}"),
        ("GeomBaBeforeMin", f"{min(ba_b):.2f}"),
        ("GeomBaBeforeMax", f"{max(ba_b):.2f}"),
        ("GeomBaAfterMin", f"{min(ba_a):.2f}"),
        ("GeomBaAfterMax", f"{max(ba_a):.2f}"),
        ("GeomBaHoldoutMin", f"{min(ba_h):.2f}"),
        ("GeomBaHoldoutMax", f"{max(ba_h):.2f}"),
        ("GeomCovMin", f"{min(cov):.1f}"),
        ("GeomCovMax", f"{max(cov):.1f}"),
    ]
    out = ["% Generated by scripts/build_geom_diagnostics.py; do not edit manually."]
    for k, v in pairs:
        out.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    return "\n".join(out) + "\n"


def main():
    rows = load_rows()
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "geom_diagnostics_zh.tex").write_text(build_table(rows, "zh"), encoding="utf-8")
    (GEN / "geom_diagnostics_en.tex").write_text(build_table(rows, "en"), encoding="utf-8")
    (GEN / "geom_macros.tex").write_text(build_macros(rows), encoding="utf-8")
    print("Wrote geom_diagnostics_{zh,en}.tex and geom_macros.tex")


if __name__ == "__main__":
    main()
