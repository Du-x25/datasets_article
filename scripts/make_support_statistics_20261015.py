"""Describe the existing evaluation support; never alter masks or model results.

This read-only audit checks the saved mask and TIFF identities, reproduces the
SSIM centre definition, and unions the saved LPIPS rectangles. It performs no
training, inference, rescoring, or human-quality acceptance.
"""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

import numpy as np
from PIL import Image
from scipy.ndimage import binary_erosion

ROOT = Path(__file__).resolve().parents[1]
PIPE = Path(r"D:\USTC\Gen\v3_pipeline")
SUPPORT = PIPE / "outputs/draft_support_v2_20261002/manifest.json"
DATASET = PIPE / "configs/v3_scene_manifest.json"
GEOMETRY_ROOT = PIPE / "outputs/v3_geometric_privacy_support"
OUT = ROOT / "figures/source_data"
GENERATED = ROOT / "generated"
Image.MAX_IMAGE_PIXELS = None


def sha(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def mask(path: Path) -> np.ndarray:
    with Image.open(path) as im:
        return np.asarray(im) > 0


def pct(n: int, denominator: int) -> float:
    return 100.0 * n / denominator if denominator else 0.0


def write_csv(path: Path, records: list[dict]) -> None:
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(records[0]))
        writer.writeheader()
        writer.writerows(records)


def write_tables(records: list[dict], bands: list[dict], total: dict) -> None:
    lookup = {(r["site"], r["modality"]): r for r in bands}
    for lang in ["zh", "en"]:
        head = (
            ["地点", r"\shortstack{公共支持\\百万像素}", r"\shortstack{占画布\\(\%)}",
             r"\shortstack{SSIM 中心\\百万个}", "窗口", r"\shortstack{LPIPS\\矩形数}",
             r"\shortstack{去重覆盖\\百万像素}", r"\shortstack{覆盖/公共\\(\%)}"]
            if lang == "zh" else
            ["Site", r"\shortstack{Common\\Mpx}", r"\shortstack{Canvas\\(\%)}",
             r"\shortstack{SSIM centres\\million}", "Windows", r"\shortstack{LPIPS\\rectangles}",
             r"\shortstack{Unique area\\Mpx}", r"\shortstack{Area/common\\(\%)}"]
        )
        lines = ["% Generated by make_support_statistics_20261015.py; counts use saved support.",
                 r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrrr@{}}", r"\toprule",
                 " & ".join(head) + r" \\", r"\midrule"]
        for r in records + [total]:
            if r is total:
                lines.append(r"\midrule")
            label = ("合计" if lang == "zh" else "Total") if r is total else r["site"]
            cells = [label, f'{r["common_valid_pixels"] / 1e6:.3f}',
                     f'{r["common_canvas_pct"]:.2f}', f'{r["ssim_centres"] / 1e6:.3f}',
                     str(r["windows"]), str(r["lpips_rectangles"]),
                     f'{r["lpips_unique_pixels"] / 1e6:.3f}', f'{r["lpips_common_pct"]:.2f}']
            lines.append(" & ".join(cells) + r" \\")
        lines += [r"\bottomrule", r"\end{tabular*}"]
        (GENERATED / f"support_statistics_{lang}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

        head = (["地点", r"\shortstack{几何/隐私排除\\占画布 (\%)}", r"\shortstack{共同 DN 排除\\占几何/隐私域 (\%)}"]
                if lang == "zh" else
                ["Site", r"\shortstack{Geometry/privacy excluded\\of canvas (\%)}", r"\shortstack{Joint DN excluded\\of geometry/privacy domain (\%)}"])
        lines = ["% Geometry/privacy is a combined existing layer; no human quality layer exists.",
                 r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrr@{}}", r"\toprule",
                 " & ".join(head) + r" \\", r"\midrule"]
        for r in records + [total]:
            if r is total:
                lines.append(r"\midrule")
            label = ("合计" if lang == "zh" else "Total") if r is total else r["site"]
            lines.append(f'{label} & {r["geometry_privacy_excluded_canvas_pct"]:.3f} & {r["joint_dn_excluded_geometry_privacy_pct"]:.2f}' + r" \\")
        lines += [r"\bottomrule", r"\end{tabular*}"]
        (GENERATED / f"support_exclusions_{lang}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

        head = (["地点"] if lang == "zh" else ["Site"]) + ["RGB", "B1", "B2", "B3", "B4", "B5"]
        lines = ["% Each cell = percent zero / percent >= 250, denominator geometry/privacy pixels.",
                 r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrr@{}}", r"\toprule",
                 " & ".join(head) + r" \\", r"\midrule"]
        for r in records:
            cells = [r["site"]]
            for name in ["RGB", "B1", "B2", "B3", "B4", "B5"]:
                b = lookup[(r["site"], name)]
                cells.append(f'{b["zero_geometry_privacy_pct"]:.2f}/{b["ge250_geometry_privacy_pct"]:.2f}')
            lines.append(" & ".join(cells) + r" \\")
        lines += [r"\bottomrule", r"\end{tabular*}"]
        (GENERATED / f"support_dynamic_range_{lang}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    support = json.loads(SUPPORT.read_text(encoding="utf-8"))
    dataset = json.loads(DATASET.read_text(encoding="utf-8"))
    geo_manifest_path = GEOMETRY_ROOT / "manifest.json"
    geo_manifest = json.loads(geo_manifest_path.read_text(encoding="utf-8"))
    assert sha(DATASET) == support["dataset_sha256"] == geo_manifest["source_manifest_sha256"]
    data_root = Path(dataset["root"])
    trace: list[dict] = []

    def checked(path: Path, expected: str | None = None) -> None:
        digest = sha(path)
        assert expected is None or digest == expected, f"Identity mismatch: {path}"
        trace.append({"path": str(path), "sha256": digest,
                      "expected_sha256_matched": True if expected is not None else None})

    results_path = PIPE / "outputs/summary_v2_20261005/site_records.csv"
    for path in [SUPPORT, DATASET, geo_manifest_path, PIPE / "v3core.py", PIPE / "run_support.py",
                 Path(__file__).resolve(), results_path]:
        checked(path)
    records, band_records = [], []
    for site in sorted(support["scenes"], key=lambda s: int(s[1:])):
        s = support["scenes"][site]
        common_path = SUPPORT.parent / s["mask"]
        gp_path = GEOMETRY_ROOT / f"{site}.png"
        joint_path = data_root / "usability_masks" / site / "joint.png"
        checked(common_path, s["mask_sha256"])
        checked(gp_path, s["geometry_sha256"])
        assert sha(gp_path) == geo_manifest["sites"][site]["mask_sha256"]
        checked(joint_path, s["joint_sha256"])
        common, gp, joint = map(mask, [common_path, gp_path, joint_path])
        assert list(common.shape) == s["shape"]
        assert common.shape == gp.shape == joint.shape
        assert np.array_equal(common, gp & joint)
        n, g, valid = common.size, int(gp.sum()), int(common.sum())
        assert valid == s["valid_pixels"]
        calculated_joint = np.ones(common.shape, dtype=bool)
        for name, info in dataset["scenes"][site].items():
            path = data_root / info["path"]
            checked(path, info["sha256"])
            with Image.open(path) as im:
                a = np.asarray(im)
            assert list(a.shape) == info["shape"] and str(a.dtype) == info["dtype"]
            low, high = a == 0, a >= 250
            if a.ndim == 3:
                low, high = low.any(axis=2), high.any(axis=2)
            calculated_joint &= ~(low | high)
            low_n, high_n = int((low & gp).sum()), int((high & gp).sum())
            band_records.append(dict(site=site, modality=name, geometry_privacy_pixels=g,
                                     zero_pixels=low_n, ge250_pixels=high_n,
                                     zero_geometry_privacy_pct=pct(low_n, g),
                                     ge250_geometry_privacy_pct=pct(high_n, g)))
        assert np.array_equal(gp & calculated_joint, common), f"DN reconstruction mismatch: {site}"
        ssim_n = int(binary_erosion(common, structure=np.ones((11, 11), bool), border_value=0).sum())
        lpips_area = np.zeros(common.shape, dtype=bool)
        for x, y, w, h in s["lpips_rectangles"]:
            assert min(x, y) >= 0 and (w, h) == (128, 128)
            assert x + w <= common.shape[1] and y + h <= common.shape[0]
            assert common[y:y+h, x:x+w].all()
            lpips_area[y:y+h, x:x+w] = True
        area_n = int(lpips_area.sum())
        for x, y, w, h in s["windows"]:
            assert min(x, y) >= 0 and x + w <= common.shape[1] and y + h <= common.shape[0]
            assert (w, h) == (256, 256) and gp[y:y+h, x:x+w].all()
            assert common[y:y+h, x:x+w].sum() >= support["minimum_fraction"] * w * h
        row = dict(site=site, height=common.shape[0], width=common.shape[1], canvas_pixels=n,
                   geometry_privacy_pixels=g, geometry_privacy_excluded_pixels=n-g,
                   geometry_privacy_excluded_canvas_pct=pct(n-g, n),
                   joint_dn_excluded_pixels=g-valid, joint_dn_excluded_geometry_privacy_pct=pct(g-valid, g),
                   common_valid_pixels=valid, common_canvas_pct=pct(valid, n),
                   ssim_centres=ssim_n, ssim_common_pct=pct(ssim_n, valid), windows=len(s["windows"]),
                   lpips_rectangles=len(s["lpips_rectangles"]), lpips_unique_pixels=area_n,
                   lpips_common_pct=pct(area_n, valid))
        records.append(row)
        print(json.dumps(row), flush=True)
    summed = ["canvas_pixels", "geometry_privacy_pixels", "geometry_privacy_excluded_pixels",
              "joint_dn_excluded_pixels", "common_valid_pixels", "ssim_centres", "windows",
              "lpips_rectangles", "lpips_unique_pixels"]
    total = {key: sum(r[key] for r in records) for key in summed}
    total.update(site="Total",
                 geometry_privacy_excluded_canvas_pct=pct(total["geometry_privacy_excluded_pixels"], total["canvas_pixels"]),
                 joint_dn_excluded_geometry_privacy_pct=pct(total["joint_dn_excluded_pixels"], total["geometry_privacy_pixels"]),
                 common_canvas_pct=pct(total["common_valid_pixels"], total["canvas_pixels"]),
                 ssim_common_pct=pct(total["ssim_centres"], total["common_valid_pixels"]),
                 lpips_common_pct=pct(total["lpips_unique_pixels"], total["common_valid_pixels"]))
    assert (total["common_valid_pixels"], total["windows"], total["lpips_rectangles"]) == (88861466, 5893, 1541)
    by_site = {row["site"]: row for row in records}
    with results_path.open(encoding="utf-8-sig", newline="") as f:
        result_rows = list(csv.DictReader(f))
    for result in result_rows:
        row = by_site[result["site"]]
        assert int(result["valid_pixels"]) == row["common_valid_pixels"]
        assert int(result["lpips_rectangles"]) == row["lpips_rectangles"]
        assert abs(float(result["lpips_valid_coverage"]) - row["lpips_common_pct"] / 100.0) <= 0.000050001
    OUT.mkdir(parents=True, exist_ok=True)
    GENERATED.mkdir(parents=True, exist_ok=True)
    write_csv(OUT / "support_statistics_20261015.csv", records)
    write_csv(OUT / "support_dynamic_range_20261015.csv", band_records)
    report = dict(schema="descriptive-support-audit-v1", support_status=support["status"],
                  support_manifest=str(SUPPORT), support_manifest_sha256=sha(SUPPORT),
                  dataset_manifest_sha256=sha(DATASET), source_files=trace,
                  checks={"saved_result_rows_matched": len(result_rows),
                          "all_60_tiff_hashes_match": True,
                          "all_30_saved_support_mask_hashes_match": True,
                          "dn_reconstruction_matches_common_support_exactly": True},
                  definitions={
                      "geometry_privacy": "Saved combined binary mask; denominator is the released cropped canvas, not original uncropped acquisition area.",
                      "common": "Saved geometry/privacy AND all eight scalar channels (RGB plus B1-B5) strictly 0 < DN < 250; reconstructed from TIFFs and checked exactly.",
                      "ssim_centres": "scipy.ndimage.binary_erosion(common, structure=ones((11,11), bool), border_value=0), identical to v3core.evaluate.",
                      "lpips_unique": "Union of the saved fully valid 128x128 rectangles, counted once per pixel; percentage denominator is common valid pixels.",
                      "windows": "Saved 256x256 windows, whole-window geometry/privacy and at least 50 percent common support; overlap permitted.",
                      "zero_ge250": "Percent of geometry/privacy pixels: DN == 0 / DN >= 250. RGB counts a pixel if any RGB channel meets the threshold; fractions may overlap and cannot be summed into a joint rate.",
                      "totals": "Summed pixel/count quantities; percentage rows use summed numerator and denominator, not means of site percentages."},
                  limitations=["Provisional after exploration, not human frozen or accepted quality.",
                               "Combined geometry/privacy layer does not separately estimate the causes of exclusion or cropped-out acquisition area.",
                               "No saved independent human-quality or temporal-change mask is represented; these exclusions cannot be reported as zero.",
                               "DN rail fractions describe the saved 8-bit processed product, not a sensor saturation or radiometric-calibration measurement.",
                               "No training, inference, rescoring or data/support change was performed."],
                  totals=total, sites=records, dynamic_range=band_records)
    (OUT / "support_statistics_20261015.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_tables(records, band_records, total)
    print("TOTAL " + json.dumps(total), flush=True)


if __name__ == "__main__":
    main()
